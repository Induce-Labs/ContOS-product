-- Rebuild each user-owned table so user_email is physical column #1.
-- Postgres cannot INSERT a column at position 1 without a table rewrite.

CREATE OR REPLACE FUNCTION public.contos_rebuild_table_user_email_first(p_table text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_catalog
AS $$
DECLARE
  v_old regclass;
  v_new_name text;
  v_backup_name text;
  v_backup_reg regclass;
  v_coldef text;
  v_cols_ordered text;
  v_insert_list text;
  v_sql text;
  v_qual text;
  v_with_check text;
  v_con record;
  v_idx record;
  v_pol record;
  v_trg record;
BEGIN
  IF p_table IS NULL OR p_table !~ '^[a-z_][a-z0-9_]*$' THEN
    RAISE EXCEPTION 'Invalid table name: %', p_table;
  END IF;

  -- Already ordered: no-op
  IF (
    SELECT c.column_name
    FROM information_schema.columns c
    WHERE c.table_schema = 'public'
      AND c.table_name = p_table
      AND c.ordinal_position = 1
  ) = 'user_email' THEN
    RETURN;
  END IF;

  v_old := format('public.%I', p_table)::regclass;
  v_new_name := p_table || '__email_first';
  v_backup_name := p_table || '__email_old';

  EXECUTE format('DROP TABLE IF EXISTS public.%I CASCADE', v_new_name);
  EXECUTE format('DROP TABLE IF EXISTS public.%I CASCADE', v_backup_name);

  SELECT string_agg(def, ', ' ORDER BY sort_key)
  INTO v_coldef
  FROM (
    SELECT
      CASE WHEN a.attname = 'user_email' THEN 0 ELSE a.attnum END AS sort_key,
      format(
        '%I %s%s%s',
        a.attname,
        pg_catalog.format_type(a.atttypid, a.atttypmod),
        CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
        CASE
          WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
          WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
          WHEN a.attgenerated = 's' THEN ''
          WHEN pg_get_expr(ad.adbin, ad.adrelid) IS NOT NULL
            THEN ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid)
          ELSE ''
        END
      ) AS def
    FROM pg_attribute a
    LEFT JOIN pg_attrdef ad
      ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
    WHERE a.attrelid = v_old
      AND a.attnum > 0
      AND NOT a.attisdropped
      AND a.attgenerated IS DISTINCT FROM 's'
  ) s;

  IF v_coldef IS NULL OR position('user_email' in v_coldef) = 0 THEN
    RAISE EXCEPTION 'Table % missing user_email column', p_table;
  END IF;

  EXECUTE format('CREATE TABLE public.%I (%s)', v_new_name, v_coldef);

  SELECT
    string_agg(quote_ident(a.attname), ', ' ORDER BY CASE WHEN a.attname = 'user_email' THEN 0 ELSE a.attnum END),
    string_agg(quote_ident(a.attname), ', ' ORDER BY CASE WHEN a.attname = 'user_email' THEN 0 ELSE a.attnum END)
  INTO v_insert_list, v_cols_ordered
  FROM pg_attribute a
  WHERE a.attrelid = v_old
    AND a.attnum > 0
    AND NOT a.attisdropped
    AND a.attgenerated IS DISTINCT FROM 's';

  EXECUTE format(
    'INSERT INTO public.%I (%s) SELECT %s FROM public.%I',
    v_new_name, v_insert_list, v_cols_ordered, p_table
  );

  -- Drop inbound FKs that reference this table (restored by migration DO block below)
  FOR v_con IN
    SELECT c.conname, c.conrelid::regclass AS from_table
    FROM pg_constraint c
    WHERE c.contype = 'f' AND c.confrelid = v_old
  LOOP
    EXECUTE format('ALTER TABLE %s DROP CONSTRAINT IF EXISTS %I', v_con.from_table, v_con.conname);
  END LOOP;

  EXECUTE format('ALTER TABLE public.%I RENAME TO %I', p_table, v_backup_name);
  EXECUTE format('ALTER TABLE public.%I RENAME TO %I', v_new_name, p_table);
  v_backup_reg := format('public.%I', v_backup_name)::regclass;

  CREATE TEMP TABLE IF NOT EXISTS _email_first_cons (
    conname text PRIMARY KEY,
    def text NOT NULL
  ) ON COMMIT DROP;
  CREATE TEMP TABLE IF NOT EXISTS _email_first_idxs (
    orig_name text PRIMARY KEY,
    indexdef text NOT NULL
  ) ON COMMIT DROP;
  DELETE FROM _email_first_cons;
  DELETE FROM _email_first_idxs;

  -- Capture original names before freeing them on the backup table
  INSERT INTO _email_first_cons(conname, def)
  SELECT c.conname, pg_get_constraintdef(c.oid)
  FROM pg_constraint c
  WHERE c.conrelid = v_backup_reg
    AND c.contype IN ('p', 'u', 'c', 'f');

  INSERT INTO _email_first_idxs(orig_name, indexdef)
  SELECT c.relname, pg_get_indexdef(i.indexrelid)
  FROM pg_index i
  JOIN pg_class c ON c.oid = i.indexrelid
  WHERE i.indrelid = v_backup_reg
    AND NOT i.indisprimary
    AND NOT EXISTS (
      SELECT 1 FROM pg_constraint co WHERE co.conindid = i.indexrelid
    );

  -- Free global index/constraint names (oid-based; avoids 63-char truncation collisions)
  FOR v_idx IN
    SELECT c.oid, c.relname AS indexname
    FROM pg_index i
    JOIN pg_class c ON c.oid = i.indexrelid
    WHERE i.indrelid = v_backup_reg
  LOOP
    EXECUTE format('ALTER INDEX public.%I RENAME TO %I', v_idx.indexname, 'eold_' || v_idx.oid::text);
  END LOOP;

  FOR v_con IN
    SELECT conname, def FROM _email_first_cons
  LOOP
    EXECUTE format(
      'ALTER TABLE public.%I ADD CONSTRAINT %I %s',
      p_table, v_con.conname, v_con.def
    );
  END LOOP;

  FOR v_idx IN
    SELECT orig_name, indexdef FROM _email_first_idxs
  LOOP
    v_sql := replace(v_idx.indexdef, ' ON public.' || v_backup_name || ' ', ' ON public.' || p_table || ' ');
    v_sql := replace(v_sql, ' ON ' || v_backup_name || ' ', ' ON ' || p_table || ' ');
    BEGIN
      EXECUTE v_sql;
    EXCEPTION WHEN duplicate_table OR duplicate_object THEN
      NULL;
    END;
  END LOOP;

  IF EXISTS (SELECT 1 FROM pg_class WHERE oid = v_backup_reg AND relrowsecurity) THEN
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', p_table);
  END IF;

  FOR v_pol IN
    SELECT policyname, cmd, roles, qual, with_check
    FROM pg_policies
    WHERE schemaname = 'public' AND tablename = v_backup_name
  LOOP
    -- Renaming the table rewrites policy quals to the backup name; map back
    v_qual := replace(v_pol.qual, v_backup_name, p_table);
    v_with_check := replace(v_pol.with_check, v_backup_name, p_table);
    v_sql := format(
      'CREATE POLICY %I ON public.%I FOR %s TO %s',
      v_pol.policyname,
      p_table,
      v_pol.cmd,
      CASE
        WHEN v_pol.roles IS NULL OR v_pol.roles = '{public}' THEN 'public'
        ELSE array_to_string(ARRAY(SELECT quote_ident(x) FROM unnest(v_pol.roles) AS x), ', ')
      END
    );
    IF v_qual IS NOT NULL THEN
      v_sql := v_sql || ' USING (' || v_qual || ')';
    END IF;
    IF v_with_check IS NOT NULL THEN
      v_sql := v_sql || ' WITH CHECK (' || v_with_check || ')';
    END IF;
    EXECUTE v_sql;
  END LOOP;

  FOR v_trg IN
    SELECT pg_get_triggerdef(t.oid) AS def
    FROM pg_trigger t
    WHERE t.tgrelid = v_backup_reg AND NOT t.tgisinternal
  LOOP
    v_sql := replace(v_trg.def, ' ON public.' || v_backup_name || ' ', ' ON public.' || p_table || ' ');
    v_sql := replace(v_sql, ' ON ' || v_backup_name || ' ', ' ON ' || p_table || ' ');
    EXECUTE v_sql;
  END LOOP;

  EXECUTE format('DROP TABLE public.%I CASCADE', v_backup_name);
END;
$$;

-- Leaf / independent tables first, then competitors, then avatars (inbound FKs restored below)
SELECT public.contos_rebuild_table_user_email_first('agent_calls');
SELECT public.contos_rebuild_table_user_email_first('agent_chat_stores');
SELECT public.contos_rebuild_table_user_email_first('content_plan_items');
SELECT public.contos_rebuild_table_user_email_first('postiz_connections');
SELECT public.contos_rebuild_table_user_email_first('user_profiles');
SELECT public.contos_rebuild_table_user_email_first('instagram_scraped_content');
SELECT public.contos_rebuild_table_user_email_first('linkedin_scraped_content');
SELECT public.contos_rebuild_table_user_email_first('twitter_scraped_content');
SELECT public.contos_rebuild_table_user_email_first('instagram_content_summaries');
SELECT public.contos_rebuild_table_user_email_first('linkedin_content_summaries');
SELECT public.contos_rebuild_table_user_email_first('twitter_content_summaries');
SELECT public.contos_rebuild_table_user_email_first('competitors');
SELECT public.contos_rebuild_table_user_email_first('avatars');

-- Restore inbound FKs dropped while rebuilding parents (idempotent)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'competitors_project_id_fkey'
  ) THEN
    ALTER TABLE public.competitors
      ADD CONSTRAINT competitors_project_id_fkey
      FOREIGN KEY (avatar_id) REFERENCES public.avatars(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'content_plan_items_avatar_id_fkey'
  ) THEN
    ALTER TABLE public.content_plan_items
      ADD CONSTRAINT content_plan_items_avatar_id_fkey
      FOREIGN KEY (avatar_id) REFERENCES public.avatars(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'postiz_connections_avatar_id_fkey'
  ) THEN
    ALTER TABLE public.postiz_connections
      ADD CONSTRAINT postiz_connections_avatar_id_fkey
      FOREIGN KEY (avatar_id) REFERENCES public.avatars(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'user_profiles_onboarding_avatar_id_fkey'
  ) THEN
    ALTER TABLE public.user_profiles
      ADD CONSTRAINT user_profiles_onboarding_avatar_id_fkey
      FOREIGN KEY (onboarding_avatar_id) REFERENCES public.avatars(id) ON DELETE SET NULL;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'content_summaries_competitor_id_fkey'
  ) THEN
    ALTER TABLE public.instagram_content_summaries
      ADD CONSTRAINT content_summaries_competitor_id_fkey
      FOREIGN KEY (competitor_id) REFERENCES public.competitors(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'content_summaries_project_id_fkey'
  ) THEN
    ALTER TABLE public.instagram_content_summaries
      ADD CONSTRAINT content_summaries_project_id_fkey
      FOREIGN KEY (avatar_id) REFERENCES public.avatars(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'scraped_content_competitor_id_fkey'
  ) THEN
    ALTER TABLE public.instagram_scraped_content
      ADD CONSTRAINT scraped_content_competitor_id_fkey
      FOREIGN KEY (competitor_id) REFERENCES public.competitors(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'linkedin_content_summaries_competitor_id_fkey'
  ) THEN
    ALTER TABLE public.linkedin_content_summaries
      ADD CONSTRAINT linkedin_content_summaries_competitor_id_fkey
      FOREIGN KEY (competitor_id) REFERENCES public.competitors(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'linkedin_content_summaries_project_id_fkey'
  ) THEN
    ALTER TABLE public.linkedin_content_summaries
      ADD CONSTRAINT linkedin_content_summaries_project_id_fkey
      FOREIGN KEY (avatar_id) REFERENCES public.avatars(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'linkedin_scraped_content_competitor_id_fkey'
  ) THEN
    ALTER TABLE public.linkedin_scraped_content
      ADD CONSTRAINT linkedin_scraped_content_competitor_id_fkey
      FOREIGN KEY (competitor_id) REFERENCES public.competitors(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'twitter_content_summaries_competitor_id_fkey'
  ) THEN
    ALTER TABLE public.twitter_content_summaries
      ADD CONSTRAINT twitter_content_summaries_competitor_id_fkey
      FOREIGN KEY (competitor_id) REFERENCES public.competitors(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'twitter_content_summaries_avatar_id_fkey'
  ) THEN
    ALTER TABLE public.twitter_content_summaries
      ADD CONSTRAINT twitter_content_summaries_avatar_id_fkey
      FOREIGN KEY (avatar_id) REFERENCES public.avatars(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'twitter_scraped_content_competitor_id_fkey'
  ) THEN
    ALTER TABLE public.twitter_scraped_content
      ADD CONSTRAINT twitter_scraped_content_competitor_id_fkey
      FOREIGN KEY (competitor_id) REFERENCES public.competitors(id) ON DELETE CASCADE;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'agent_chat_stores_avatar_id_fkey'
  ) THEN
    BEGIN
      ALTER TABLE public.agent_chat_stores
        ADD CONSTRAINT agent_chat_stores_avatar_id_fkey
        FOREIGN KEY (avatar_id) REFERENCES public.avatars(id) ON DELETE CASCADE;
    EXCEPTION WHEN foreign_key_violation THEN
      RAISE NOTICE 'Skipping agent_chat_stores_avatar_id_fkey due to orphan avatar_id rows';
    END;
  END IF;
END $$;

COMMENT ON FUNCTION public.contos_rebuild_table_user_email_first(text) IS
  'Rebuild a public table so user_email is physical column 1. Used by ContOS admin migrations.';
